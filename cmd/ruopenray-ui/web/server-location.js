function stripes(colors, direction = 'h', weights = []) {
  const total = weights.length ? weights.reduce((sum, item) => sum + item, 0) : colors.length;
  let offset = 0;
  return colors.map((color, index) => {
    const size = (weights[index] || 1) / total;
    const node = direction === 'v'
      ? `<rect x="${offset * 24}" y="0" width="${size * 24}" height="18" fill="${color}"/>`
      : `<rect x="0" y="${offset * 18}" width="24" height="${size * 18}" fill="${color}"/>`;
    offset += size;
    return node;
  }).join('');
}

